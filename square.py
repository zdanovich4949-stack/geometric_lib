def area(a):

    '''
    Returns the area of square for a giver parameters.

    Parameters:
        a (float): Lenght of a square's side.
    
    Return value:
        a * a (float): Area of square.
    
    Example:
        area(10): 100
    '''

    return a * a


def perimeter(a):

    '''
    Returns the perimeter of square for a giver parameters.

    Parameters:
        a (float): Lenght of a square's side.
    
    Return value:
        4 * a (float): Perimeter of square.
    
    Example:
        perimeter(4): 16
    '''
    
    return 4 * a
    