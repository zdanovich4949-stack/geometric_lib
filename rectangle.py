def area(a, b):  

    '''
    Returns the area of rectangle for a giver parameters.

    Parameters:
        a (float): Lenght of a rectangle's side.
        b (float): Width of a rectangle's side.
    
    Return value:
        a * b (float): Area of a rectangle.
    
    Example:
        area(111,7): 777
    '''

    return a * b  

 

def perimeter(a, b):

    '''
    Returns the perimeter of rectangle for a giver parameters.

    Parameters:
        a (float): Lenght of a rectangle's side.
        b (float): Width of a rectangle's side.
    
    Return value:
        2 * (a + b) (float): Perimeter of a rectangle.
        
    Example:
        perimeter(5,10): 30
    '''

    return 2 * (a + b)